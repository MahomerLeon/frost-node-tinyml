"""Convert the float model to TFLite int8 and measure the F1 change (R3).

Run from the repository root, after ml/train.py:
    python ml/convert_tflite.py

Output (N = dataset_version):
    ml/models/model_vN.tflite          int8 model
    ml/models/metrics_vN_int8.json     float vs int8 on the same test split
    ml/models/test_vectors_vN.csv      test rows to validate on the devices
    firmware/inference/model_data.h       C array + preprocessing constants
    firmware/pico_benchmark/model_data.h  the same file, for the Pico

Design decisions:
- Full integer quantization: weights, activations, input and output are all
  int8, so the ESP32-S3 needs no floating point inside the model.
- The representative dataset (used to measure the range of each tensor)
  comes from the TRAIN split only. The test split is used only to report.
"""

import argparse
import json

import numpy as np
import tensorflow as tf
from tensorflow import keras

from dataset_utils import (DEFAULT_CONFIG, REPO_DIR, load_config,
                           load_dataset, models_dir)
from train import metrics_from_predictions, print_metrics


def quantize(values, scale, zero_point):
    """float -> int8 with the scale and zero point stored in the model."""
    quantized = np.round(values / scale + zero_point)
    return np.clip(quantized, -128, 127).astype(np.int8)


def run_int8(interpreter, quantized_inputs):
    """Run the int8 model row by row. Returns the raw int8 outputs."""
    input_index = interpreter.get_input_details()[0]["index"]
    output_index = interpreter.get_output_details()[0]["index"]
    outputs = []
    for row in quantized_inputs:
        interpreter.set_tensor(input_index, row[np.newaxis, :])
        interpreter.invoke()
        outputs.append(interpreter.get_tensor(output_index)[0].copy())
    return np.array(outputs)


def write_header(path, model_bytes, preprocessing, config):
    """Write the model as a C array, plus the constants the firmware needs."""
    columns = preprocessing["feature_columns"]
    step = config["grid_minutes"]
    lines = [
        "// Generated by ml/convert_tflite.py. Do not edit by hand.",
        f"// Dataset version: {config['dataset_version']}",
        "#pragma once",
        "#include <stdint.h>",
        "",
        f"#define MODEL_NUM_INPUTS {len(columns)}",
        f"#define MODEL_NUM_CLASSES {preprocessing['num_classes']}",
        f"#define MODEL_GRID_MINUTES {step}",
        f"#define MODEL_WINDOW_STEPS {config['window_hours'] * 60 // step}",
        f"#define MODEL_USES_PRESSURE {int(any('pressure' in c for c in columns))}",
        "",
        "// Input order: " + ", ".join(columns),
        "// Standardization: input = (value - mean) / std",
        "const float MODEL_INPUT_MEAN[MODEL_NUM_INPUTS] = {"
        + ", ".join(f"{v:.6f}f" for v in preprocessing["mean"]) + "};",
        "const float MODEL_INPUT_STD[MODEL_NUM_INPUTS] = {"
        + ", ".join(f"{v:.6f}f" for v in preprocessing["std"]) + "};",
        "",
        f"const unsigned int g_model_data_len = {len(model_bytes)};",
        "alignas(16) const unsigned char g_model_data[] = {",
    ]
    for start in range(0, len(model_bytes), 12):
        chunk = model_bytes[start:start + 12]
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in chunk) + ",")
    lines.append("};")
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--config", default=str(DEFAULT_CONFIG))
    config = load_config(parser.parse_args().config)
    version = config["dataset_version"]
    folder = models_dir(config)

    model = keras.models.load_model(folder / f"model_v{version}.keras")
    preprocessing = json.loads(
        (folder / f"model_v{version}_preprocessing.json").read_text(encoding="utf-8"))
    columns = preprocessing["feature_columns"]
    n_classes = preprocessing["num_classes"]
    mean = np.array(preprocessing["mean"])
    std = np.array(preprocessing["std"])

    dataset = load_dataset(config)

    def inputs_of(part):
        return ((part[columns].to_numpy() - mean) / std).astype("float32")

    train = dataset[dataset["split"] == "train"]
    test = dataset[dataset["split"] == "test"]
    x_test, y_test = inputs_of(test), test["label"].to_numpy()

    # ---- representative dataset: a random sample of TRAIN rows ----
    rng = np.random.default_rng(config["training"]["seed"])
    n_samples = min(config["conversion"]["representative_samples"], len(train))
    sample = inputs_of(train.iloc[rng.choice(len(train), n_samples, replace=False)])

    def representative_dataset():
        for row in sample:
            yield [row[np.newaxis, :]]

    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = representative_dataset
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8
    # Use ONE scale per dense layer instead of one scale per neuron
    # ("per-channel"). Found by testing on the ESP32-S3: with per-channel
    # dense weights, the TFLite Micro library used in the firmware
    # (Chirale_TensorFLowLite 2.0.0) gave outputs different from the PC.
    # With this option the node reproduces the PC model exactly.
    converter._experimental_disable_per_channel_quantization_for_dense_layers = True
    model_bytes = converter.convert()

    tflite_file = folder / f"model_v{version}.tflite"
    tflite_file.write_bytes(model_bytes)

    # ---- evaluate float and int8 on the SAME test split ----
    float_predicted = np.argmax(model.predict(x_test, batch_size=4096, verbose=0), axis=1)
    float_metrics = metrics_from_predictions(y_test, float_predicted, n_classes)

    interpreter = tf.lite.Interpreter(model_content=model_bytes)
    interpreter.allocate_tensors()
    scale, zero_point = interpreter.get_input_details()[0]["quantization"]
    q_test = quantize(x_test, scale, zero_point)
    int8_outputs = run_int8(interpreter, q_test)
    int8_predicted = np.argmax(int8_outputs, axis=1)
    int8_metrics = metrics_from_predictions(y_test, int8_predicted, n_classes)

    print_metrics("float model, test", float_metrics)
    print_metrics("int8 model, test", int8_metrics)

    change = int8_metrics["f1_macro"] - float_metrics["f1_macro"]
    agreement = float(np.mean(float_predicted == int8_predicted))
    print("\n--- float vs int8 (R3) ---")
    print(f"F1 macro float: {float_metrics['f1_macro']:.4f}")
    print(f"F1 macro int8:  {int8_metrics['f1_macro']:.4f}")
    print(f"change (int8 - float): {change:+.4f}")
    for label in float_metrics["per_class"]:
        f1_float = float_metrics["per_class"][label]["f1"]
        f1_int8 = int8_metrics["per_class"][label]["f1"]
        print(f"class {label}: F1 float {f1_float:.4f}, int8 {f1_int8:.4f}, "
              f"change {f1_int8 - f1_float:+.4f}")
    print(f"test rows where both models predict the same class: {100 * agreement:.2f}%")

    # ---- size and tensor arena ----
    size_kb = len(model_bytes) / 1024
    # Activations: one int8 byte per value of the input and of each layer output
    activation_bytes = len(columns) + sum(layer.units for layer in model.layers)
    print("\n--- size ---")
    print(f"model_v{version}.tflite: {len(model_bytes)} bytes ({size_kb:.2f} KB)")
    print(f"activation tensors: about {activation_bytes} bytes")
    print("Tensor arena: the activations are only a lower bound. TFLite Micro "
          "also stores its own bookkeeping structures in the arena, and their "
          "size depends on the library version. The real value must be read on "
          "the ESP32-S3 with interpreter.arena_used_bytes() (BENCHMARK mode).")

    (folder / f"metrics_v{version}_int8.json").write_text(json.dumps({
        "dataset_version": version,
        "tflite_bytes": len(model_bytes),
        "activation_bytes_lower_bound": activation_bytes,
        "f1_macro_float": float_metrics["f1_macro"],
        "f1_macro_int8": int8_metrics["f1_macro"],
        "f1_macro_change": change,
        "prediction_agreement": agreement,
        "float_test": float_metrics,
        "int8_test": int8_metrics,
    }, indent=2), encoding="utf-8")

    # ---- test vectors for on-device validation ----
    n_vectors = min(config["conversion"]["device_test_vectors"], len(q_test))
    chosen = rng.choice(len(q_test), n_vectors, replace=False)
    header = ([f"in_{i}" for i in range(len(columns))]
              + [f"out_{c}" for c in range(n_classes)] + ["label"])
    rows = np.column_stack([q_test[chosen], int8_outputs[chosen], y_test[chosen]])
    np.savetxt(folder / f"test_vectors_v{version}.csv", rows, fmt="%d",
               delimiter=",", header=",".join(header), comments="")

    print(f"\nsaved: {tflite_file}")
    # The same header goes to every firmware that runs the model
    # (ESP32-S3 node and Raspberry Pi Pico benchmark)
    for path in config["paths"]["firmware_model_headers"]:
        header_file = REPO_DIR / path
        write_header(header_file, model_bytes, preprocessing, config)
        print(f"saved: {header_file}")
    print(f"saved: {n_vectors} test vectors for the device")


if __name__ == "__main__":
    main()
